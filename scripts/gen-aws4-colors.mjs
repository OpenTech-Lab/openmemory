#!/usr/bin/env node
// Regeneratable generator: reads draw.io's AWS4 sidebar definitions (Sidebar-AWS4.js)
// and rewrites the AWS4_RESOURCE_COLORS map in apps/web/lib/drawio.ts — the icon->colour
// table normalizeAws4ResourceIcons() uses to backfill a missing fillColor on AWS4 resource
// icons. Not part of the build; re-run manually if draw.io's AWS4 stencil colours change.
//
// Usage: node scripts/gen-aws4-colors.mjs
// Reads <webapp>/js/diagramly/sidebar/Sidebar-AWS4.js from a drawio checkout, resolved via
// the DRAWIO_WEBAPP_PATH env var (defaults to ../drawio/src/main/webapp relative to the repo
// root, matching docker-compose.yml's default for the drawio service).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const webappPath = path.resolve(repoRoot, process.env.DRAWIO_WEBAPP_PATH ?? '../drawio/src/main/webapp');
const sidebarPath = path.join(webappPath, 'js/diagramly/sidebar/Sidebar-AWS4.js');
const targetPath = path.join(repoRoot, 'apps/web/lib/drawio.ts');

// Sidebar-AWS4.js doesn't contain literal resIcon=...;fillColor=... pairs. It builds styles
// from scoped prefix variables (e.g. `var n2 = '...fillColor=#XXXXXX...' + mxConstants.STYLE_SHAPE
// + "=mxgraph.aws4.";`) and then uses them per entry: `n2 + 'resourceIcon;resIcon=' + gn + '.athena;'`.
// The prefix vars are redefined per palette section, so track the most recent definition of
// each var name while scanning top-to-bottom, and dedupe icon names by last-write-wins — a few
// icon names (e.g. sagemaker_2) are legitimately re-listed under a different palette section
// with that section's colour.
const lines = readFileSync(sidebarPath, 'utf8').split('\n');
const vars = {};
const pairs = new Map();
const varDef = /^\s*var\s+(\w+)\s*=\s*(.*)$/;
const usage = /(\w+)\s*\+\s*['"]resourceIcon;resIcon=['"]\s*\+\s*gn\s*\+\s*['"]\.([a-z0-9_]+)/gi;

for (const line of lines) {
  const declared = varDef.exec(line);
  if (declared && /STYLE_SHAPE|fillColor=/.test(declared[2])) {
    const fillColor = /fillColor=(#[0-9A-Fa-f]{6})/.exec(declared[2]);
    vars[declared[1]] = fillColor ? fillColor[1] : null;
  }

  let match;
  while ((match = usage.exec(line)) !== null) {
    const color = vars[match[1]];
    if (color) pairs.set(match[2], color);
  }
}

if (pairs.size === 0) {
  throw new Error(`No icon/colour pairs extracted from ${sidebarPath} — check the sidebar file format.`);
}

const quoteKey = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : `'${name}'`);
const sortedNames = [...pairs.keys()].sort();
const entries = sortedNames.map((name) => `  ${quoteKey(name)}: '${pairs.get(name)}',`).join('\n');

const generatedBlock = `// Generated by scripts/gen-aws4-colors.mjs from draw.io's AWS4 sidebar definitions
// (Sidebar-AWS4.js). Do not hand-edit — re-run the script to regenerate after draw.io's
// AWS4 stencil colours change upstream.
const AWS4_RESOURCE_COLORS: Record<string, string> = {
${entries}
};`;

const source = readFileSync(targetPath, 'utf8');
const blockPattern = /(?:\/\/[^\n]*\n)*const AWS4_RESOURCE_COLORS: Record<string, string> = \{[\s\S]*?\n\};/;
if (!blockPattern.test(source)) {
  throw new Error(`Could not find an AWS4_RESOURCE_COLORS block to replace in ${targetPath}.`);
}
writeFileSync(targetPath, source.replace(blockPattern, generatedBlock));

const colorCounts = new Map();
for (const color of pairs.values()) colorCounts.set(color, (colorCounts.get(color) ?? 0) + 1);
const colorSummary = [...colorCounts.entries()].sort((a, b) => b[1] - a[1]).map(([c, n]) => `${c}×${n}`).join(', ');

console.log(`Patched ${targetPath} with ${pairs.size} AWS4 resource icon colours (${colorCounts.size} distinct).`);
console.log(colorSummary);
